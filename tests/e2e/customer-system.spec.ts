import {test,expect} from '@playwright/test';
import {issueReviewSession} from '../../lib/internal-review/auth';
import {randomUUID} from 'node:crypto';
const origin=process.env.E2E_ORIGIN||'http://localhost:3000';
for(const width of[360,390])test(`customer system ${width}: fresh input, whole basic groups, reload and PDF`,async({browser})=>{
 test.setTimeout(90000);
 const c=await browser.newContext({baseURL:origin,viewport:{width,height:850}});
 await c.addCookies([{name:'tuvi_internal',value:issueReviewSession(),url:origin,httpOnly:true,sameSite:'Strict'}]);
 const page=await c.newPage(),errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/internal/customer',{waitUntil:'domcontentloaded'});
 await page.getByLabel('Tên hiển thị',{exact:true}).fill('Kiểm thử luồng chung '+randomUUID().slice(0,8));
 await page.getByLabel('Ngày sinh',{exact:true}).selectOption('9');await page.getByLabel('Tháng sinh',{exact:true}).selectOption('2');await page.getByLabel('Năm sinh',{exact:true}).fill('1997');
 await page.getByLabel('Giờ sinh',{exact:true}).selectOption('6');await page.getByLabel('Nữ',{exact:true}).check();
 await page.getByRole('button',{name:'Tiếp tục →',exact:true}).click();
 await expect(page.getByRole('region',{name:'Thông tin sẽ dùng để tạo báo cáo'})).toContainText('09/02/1997');
 await page.getByRole('button',{name:'← Sửa thông tin',exact:true}).click();
 await page.getByLabel('Ngày sinh',{exact:true}).selectOption('10');
 await page.getByRole('button',{name:'Tiếp tục →',exact:true}).click();
 await expect(page.getByRole('region',{name:'Thông tin sẽ dùng để tạo báo cáo'})).toContainText('10/02/1997');
 await page.getByRole('button',{name:'Xác nhận và tạo báo cáo',exact:true}).click();
 await page.waitForURL(/\/internal\/readings\?id=/);
 await page.getByRole('link',{name:'Xem báo cáo chi tiết →',exact:true}).click();
 const url=page.url(),id=new URL(url).searchParams.get('id')!;
 await expect(page.locator('[data-customer-version]')).toHaveAttribute('data-customer-version','1.47.0');
 const detailed=await page.locator('[data-customer-text]').allTextContents();expect(detailed.length).toBeGreaterThan(0);expect(detailed.join(' ')).not.toContain('chờ biên tập');
 await expect(page.locator('[data-customer-palace]')).toHaveCount(12);
 await page.locator('.toc-disclosure>.disclosure-toggle').focus();await page.keyboard.press('Enter');
 await page.locator('nav[aria-label="Mục lục báo cáo"] a').first().click();await expect(page.locator('#life')).toBeInViewport();
 const evidence=page.locator('[data-customer-evidence]').first();await evidence.locator(':scope>.disclosure-toggle').focus();await page.keyboard.press('Enter');await expect(evidence).toHaveAttribute('data-open','true');await expect(evidence).toContainText('Nguồn');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.goto(url+'&mode=basic',{waitUntil:'domcontentloaded'});const basic=await page.locator('[data-customer-text]').allTextContents();for(const paragraph of basic)expect(detailed).toContain(paragraph);
 await page.goto(url,{waitUntil:'domcontentloaded'});expect(await page.locator('[data-customer-text]').allTextContents()).toEqual(detailed);
 const pdf=await c.request.get('/api/internal-readings/'+id+'/report-pdf',{timeout:60000});expect(pdf.status()).toBe(200);expect((await pdf.body()).subarray(0,4).toString()).toBe('%PDF');expect(pdf.headers()['cache-control']).toContain('no-store');expect(errors).toEqual([]);await c.close();
});
test('customer report and PDF remain private',async({request,page})=>{
 await page.goto('/internal/customer');await expect(page.locator('form')).toHaveCount(0);
 expect((await request.post('/api/internal-readings',{data:{}})).status()).toBe(401);
 expect((await request.get('/api/internal-readings/'+randomUUID()+'/report-pdf')).status()).toBe(401);
});
